/**
 * @file generators.hpp
 * @brief Заголовочный файл с объявлениями трёх модифицированных генераторов
 *        псевдослучайных чисел
 *
 * В этом файле объявлены функции и глобальные переменные для генераторов:
 * - LCG с битовым перемешиванием (генератор 1)
 * - Фибоначчи с запаздыванием и переносом (генератор 2)
 * - RotMix – метод перемешивания с циклическими сдвигами (генератор 3)
 *
 * Каждый генератор предоставляет две функции:
 * - `*_seed()` – инициализация начальным значением
 * - `next_*()` – получение следующего 32-битного псевдослучайного числа
 */

#ifndef GENERATORS_HPP
#define GENERATORS_HPP

#include <cmath>
#include <fstream>
#include <iostream>
#include <string>
#include <vector>

using namespace std;

/** @brief Текущее состояние модифицированного LCG-генератора */
extern uint32_t lcg_state;
/**
 * @brief Устанавливает начальное значение для модифицированного LCG-генератора
 * посредством lcg_state
 *
 * @param seed Начальное значение - 32-битное целое число
 */
void lcg_seed(uint32_t seed);
/**
 * @brief Генерирует следующее псевдослучайное число, используя LCG с
 *        битовым перемешиванием
 *
 * Алгоритм следующий:
 * - Обновляет состояние по формуле LCG: `state = 1664525 * state + 1013904223`
 * - Применяет к результату перемешивание: `out ^= out >> 16; out ^= out << 13;
 *   out ^= out >> 5;`
 *
 * @return Следующее 32-битное псевдослучайное число
 */
uint32_t next_lcg();

/** @brief Буфер для хранения последних 17 значений генератора 2 */
extern uint32_t lfib_buffer[17];
/** @brief Текущий индекс в буфере */
extern int lfib_index;
/** @brief Значение переноса для генератора 2 */
extern uint32_t lfib_carry;
/**
 * @brief Инициализация генератора Фибоначчи с запаздыванием
 *
 * Заполняет буфер `lfib_buffer` значениями, полученными с помощью
 * вспомогательного LCG `s = s * 1103515245 + 12345`, обнуляет перенос
 *
 * @param seed Начальное значение, которое используется для инициализации буфера
 */
void lagfib_carry_seed(uint32_t seed);
/**
 * @brief Генерирует следующее число по алгоритму запаздывающего Фибоначчи с
 *        переносом
 *
 * Формула:
 * - `new_val = (buffer[n-1] + buffer[n-5]) ^ (buffer[n-1] >> 3) + carry`
 * - `carry = ((a+b) >> 28) ^ (new_val >> 28) & 0xF`
 * - дополнительное перемешивание в виде XOR со сдвигами
 *
 * @return Следующее 32-битное псевдослучайное число
 */
uint32_t next_lagfib_carry();

/** @brief Массив состояний из 3 слов для генератора RotMix */
extern uint32_t rot_state[3];
/**
 * @brief Выполняет циклический сдвиг 32-битного числа влево
 *
 * @param x Исходное число
 * @param bits Количество бит для сдвига
 * @return Результат циклического сдвига
 */
uint32_t rot_left(uint32_t x, int bits);
/**
 * @brief Выполняет циклический сдвиг 32-битного числа вправо
 *
 * @param x Исходное число
 * @param bits Количество бит для сдвига
 * @return Результат циклического сдвига
 */
uint32_t rot_right(uint32_t x, int bits);
/**
 * @brief Инициализация генератора RotMix
 *
 * Заполняет массив `rot_state` тремя числами, полученными с помощью LCG:
 * `s = s * 1664525 + 1013904223`
 *
 * @param seed Начальное значение
 */
void rotmix_seed(uint32_t seed);
/**
 * @brief Генерирует следующее число по алгоритму RotMix
 *
 * Обновляет три состояния:
 * - `new_a = rot_left(a,7) ^ rot_right(b,13) ^ c`
 * - `new_b = rot_left(b,11) ^ rot_right(c,17) ^ a`
 * - `new_c = rot_left(c,19) ^ rot_right(a,23) ^ b`
 * Затем выходное значение:
 * - `out = new_a ^ new_b ^ new_c`
 * - `out ^= out >> 16; out *= 0x85EBCA77; out ^= out >> 13`
 *
 * @return Следующее 32-битное псевдослучайное число
 */
uint32_t next_rotmix();

#endif